// Content loaders. Structure is bundled eagerly (small); chapter content, notes and flashcards are lazy chunks.
// Form 4 content comes from the server instead when accounts are on (see REMOTE); Form 3 is free and always bundled.
import manifest from './manifest.json'
import { fetchKind, fetchRow } from './remote'
import { chapterId, type Form, formOf, subtopicId, SUBJECT_IDS } from './ids'
import type { Bridge, ChapterContent, Flashcard, Formula, Lang, NotesFile, Question, RawSubject, SubjectId } from './schema'

export interface Subtopic { id: string; code: string; title: Lang; learningStandards: string[] }
export interface Chapter {
  id: string
  subjectId: SubjectId
  form: Form
  number: number
  title: Lang
  theme?: Lang
  subtopics: Subtopic[]
  /** Has a written intro + questions (content/form<N>/<subject>/<chapter>.json). */
  written: boolean
}
export interface Subject { id: SubjectId; form: Form; name: Lang; short?: Lang; color: string; chapters: Chapter[] }

// With accounts on, Form 4 chapter content, notes and flashcards come from the server (only what the user may see)
// and are NOT bundled: the constant condition below lets the bundler drop those imports entirely.
const REMOTE = !!import.meta.env.VITE_SUPABASE_URL
type Loaders<T> = Record<string, () => Promise<{ default: T }>>
type Deck = { chapterId: string; cards: Flashcard[] }
const f4Content: Loaders<ChapterContent> = import.meta.env.VITE_SUPABASE_URL ? {} : import.meta.glob<{ default: ChapterContent }>('../../content/form4/{phy,chem,bio,addmath,math,sej,pi,bm,bi}/*.json')
const f4Flash: Loaders<Deck> = import.meta.env.VITE_SUPABASE_URL ? {} : import.meta.glob<{ default: Deck }>('../../content/form4/flashcards/*.json')
const f4Notes: Loaders<NotesFile> = import.meta.env.VITE_SUPABASE_URL ? {} : import.meta.glob<{ default: NotesFile }>('../../content/form4/notes/*.json')
const f3Content = import.meta.glob<{ default: ChapterContent }>('../../content/form3/f3*/*.json')
const f3Flash = import.meta.glob<{ default: Deck }>('../../content/form3/flashcards/*.json')
const f3Notes = import.meta.glob<{ default: NotesFile }>('../../content/form3/notes/*.json')

const rawFiles = import.meta.glob<RawSubject>('../../content/form*/raw/*.json', { eager: true, import: 'default' })
const formulaFiles = import.meta.glob<Formula[]>('../../content/form*/formulas.json', { eager: true, import: 'default' })

const fileId = (path: string) => path.split('/').pop()!.replace('.json', '')
const byFile = <T>(mods: Record<string, T>) => Object.fromEntries(Object.entries(mods).map(([p, v]) => [fileId(p), v]))
const contentByChapter = byFile({ ...f4Content, ...f3Content })
const notesByChapter = byFile({ ...f4Notes, ...f3Notes })
const flashByChapter = byFile({ ...f4Flash, ...f3Flash })
const RAW = byFile(rawFiles) as Record<string, RawSubject>
/** Which chapters have content — generated by scripts/validate-content.ts, so it is known without the content itself. */
const WRITTEN = new Set(manifest.written)

/** Served from the server (protected) rather than the bundle. */
const isRemote = (id: string) => REMOTE && formOf(id) === 4

export const SUBJECTS: Subject[] = SUBJECT_IDS.filter((sid) => RAW[sid]).map((sid) => {
  const raw = RAW[sid]
  const form = formOf(sid)
  return {
    id: sid,
    form,
    name: raw.name,
    short: raw.short,
    color: raw.color,
    chapters: raw.chapters.map((c) => {
      const id = chapterId(sid, c.number)
      return {
        id, subjectId: sid, form, number: c.number, title: c.title, theme: c.theme, written: WRITTEN.has(id),
        subtopics: c.subtopics.map((s) => ({ id: subtopicId(id, s.code), code: s.code, title: s.title, learningStandards: s.learningStandards ?? [] })),
      }
    }),
  }
})

export const subjectById = Object.fromEntries(SUBJECTS.map((s) => [s.id, s])) as Record<SubjectId, Subject>
export const subjectsOf = (form: Form) => SUBJECTS.filter((s) => s.form === form)
export const ALL_CHAPTERS = SUBJECTS.flatMap((s) => s.chapters)
export const chapterById = Object.fromEntries(ALL_CHAPTERS.map((c) => [c.id, c])) as Record<string, Chapter>
export const ALL_SUBTOPICS = ALL_CHAPTERS.flatMap((c) => c.subtopics.map((s) => ({ ...s, chapterId: c.id, subjectId: c.subjectId })))
export const subtopicById = Object.fromEntries(ALL_SUBTOPICS.map((s) => [s.id, s]))
export const HAS_FLASHCARDS = manifest.flashcards.length > 0

export const FORMULAS = Object.values(formulaFiles).flat()
export const formulaById = Object.fromEntries(FORMULAS.map((f) => [f.id, f])) as Record<string, Formula>
export const formulasOf = (form: Form) => FORMULAS.filter((f) => formOf(f.subtopicId) === form)

const contentCache = new Map<string, Promise<ChapterContent | undefined>>()
let questionsPromise: Promise<Question[]> | undefined
let flashPromise: Promise<Flashcard[]> | undefined

/** Forget loaded content, e.g. after the user's access changes. */
export function resetContentMemo() {
  contentCache.clear()
  questionsPromise = undefined
  flashPromise = undefined
}

async function remoteChapter(id: string): Promise<ChapterContent | undefined> {
  const [intro, questions] = await Promise.all([
    fetchRow<Pick<ChapterContent, 'reviewed' | 'intro'>>(`intro:${id}`),
    fetchRow<Question[]>(`questions:${id}`).catch(() => undefined),
  ])
  return intro ? { chapterId: id, reviewed: intro.reviewed, intro: intro.intro, questions: questions ?? [] } : undefined
}

const localChapter = (id: string) => (contentByChapter[id] ? contentByChapter[id]().then((m) => m.default) : Promise.resolve(undefined))

/** Intro + questions of a chapter; undefined when it has none or (with accounts on) the user may not read it. */
export function loadChapterContent(id: string): Promise<ChapterContent | undefined> {
  if (!contentCache.has(id)) {
    const p = isRemote(id) ? remoteChapter(id) : localChapter(id)
    contentCache.set(id, p.catch((e) => { contentCache.delete(id); throw e }))
  }
  return contentCache.get(id)!
}

/** Every question the user may use, from both forms (callers filter by form or scope). */
export function loadAllQuestions(): Promise<Question[]> {
  const local = () => Promise.all(ALL_CHAPTERS.filter((c) => c.written && !isRemote(c.id)).map((c) => loadChapterContent(c.id)))
    .then((all) => all.flatMap((c) => c?.questions ?? []))
  questionsPromise ??= Promise.all([local(), REMOTE ? fetchKind<Question[]>('questions').then((d) => d.flat()) : Promise.resolve([])])
    .then(([a, b]) => [...a, ...b])
    .catch((e) => { questionsPromise = undefined; throw e })
  return questionsPromise
}

export function loadAllFlashcards(): Promise<Flashcard[]> {
  const local = () => Promise.all(Object.entries(flashByChapter).filter(([id]) => !isRemote(id)).map(([, load]) => load().then((m) => m.default.cards)))
    .then((d) => d.flat())
  flashPromise ??= Promise.all([local(), REMOTE ? fetchKind<Flashcard[]>('flashcards').then((d) => d.flat()) : Promise.resolve([])])
    .then(([a, b]) => [...a, ...b])
    .catch((e) => { flashPromise = undefined; throw e })
  return flashPromise
}

let bridgePromise: Promise<Bridge> | undefined
export function loadBridge(): Promise<Bridge> {
  bridgePromise ??= import('../../content/form4/bridge.json').then((m) => m.default as Bridge)
  return bridgePromise
}

export function loadNotes(chapterId: string): Promise<NotesFile | undefined> {
  if (isRemote(chapterId)) return fetchRow<NotesFile>(`notes:${chapterId}`)
  return notesByChapter[chapterId] ? notesByChapter[chapterId]().then((m) => m.default) : Promise.resolve(undefined)
}
