// Content loaders. Structure is bundled eagerly (small); chapter content, notes and flashcards are lazy chunks,
// or come from the server when accounts are on (see REMOTE).
import phyRaw from '../../content/raw/phy.json'
import chemRaw from '../../content/raw/chem.json'
import bioRaw from '../../content/raw/bio.json'
import addmathRaw from '../../content/raw/addmath.json'
import mathRaw from '../../content/raw/math.json'
import sejRaw from '../../content/raw/sej.json'
import piRaw from '../../content/raw/pi.json'
import bmRaw from '../../content/raw/bm.json'
import biRaw from '../../content/raw/bi.json'
import formulasJson from '../../content/formulas.json'
import manifest from './manifest.json'
import { fetchKind, fetchRow } from './remote'
import { chapterId, subtopicId, SUBJECT_IDS } from './ids'
import type { Bridge, ChapterContent, Flashcard, Formula, Lang, NotesFile, Question, RawSubject, SubjectId } from './schema'

export interface Subtopic { id: string; code: string; title: Lang; learningStandards: string[] }
export interface Chapter {
  id: string
  subjectId: SubjectId
  number: number
  title: Lang
  theme?: Lang
  subtopics: Subtopic[]
  /** Has a written intro + questions (content/<subject>/<chapter>.json). */
  written: boolean
}
export interface Subject { id: SubjectId; name: Lang; short?: Lang; color: string; chapters: Chapter[] }

// With accounts on, chapter content, notes and flashcards come from the server (only what the user may see) and are
// NOT bundled: the constant condition below lets the bundler drop the local imports entirely.
const REMOTE = !!import.meta.env.VITE_SUPABASE_URL
type Loaders<T> = Record<string, () => Promise<{ default: T }>>
const contentModules: Loaders<ChapterContent> = import.meta.env.VITE_SUPABASE_URL ? {} : import.meta.glob<{ default: ChapterContent }>('../../content/{phy,chem,bio,addmath,math,sej,pi,bm,bi}/*.json')
const flashModules: Loaders<{ chapterId: string; cards: Flashcard[] }> = import.meta.env.VITE_SUPABASE_URL ? {} : import.meta.glob<{ default: { chapterId: string; cards: Flashcard[] } }>('../../content/flashcards/*.json')
const notesModules: Loaders<NotesFile> = import.meta.env.VITE_SUPABASE_URL ? {} : import.meta.glob<{ default: NotesFile }>('../../content/notes/*.json')

const fileId = (path: string) => path.split('/').pop()!.replace('.json', '')
const contentByChapter = Object.fromEntries(Object.entries(contentModules).map(([p, load]) => [fileId(p), load]))
const notesByChapter = Object.fromEntries(Object.entries(notesModules).map(([p, load]) => [fileId(p), load]))
/** Which chapters have content — generated by scripts/validate-content.ts, so it is known without the content itself. */
const WRITTEN = new Set(manifest.written)
const flashByChapter = Object.fromEntries(Object.entries(flashModules).map(([p, load]) => [fileId(p), load]))

const RAW: Record<SubjectId, RawSubject> = {
  phy: phyRaw as RawSubject, chem: chemRaw as RawSubject, bio: bioRaw as RawSubject,
  addmath: addmathRaw as RawSubject, math: mathRaw as RawSubject,
  sej: sejRaw as RawSubject, pi: piRaw as RawSubject, bm: bmRaw as RawSubject, bi: biRaw as RawSubject,
}

export const SUBJECTS: Subject[] = SUBJECT_IDS.map((sid) => {
  const raw = RAW[sid]
  return {
    id: sid,
    name: raw.name,
    short: raw.short,
    color: raw.color,
    chapters: raw.chapters.map((c) => {
      const id = chapterId(sid, c.number)
      return {
        id, subjectId: sid, number: c.number, title: c.title, theme: c.theme, written: WRITTEN.has(id),
        subtopics: c.subtopics.map((s) => ({ id: subtopicId(id, s.code), code: s.code, title: s.title, learningStandards: s.learningStandards ?? [] })),
      }
    }),
  }
})

export const subjectById = Object.fromEntries(SUBJECTS.map((s) => [s.id, s])) as Record<SubjectId, Subject>
export const ALL_CHAPTERS = SUBJECTS.flatMap((s) => s.chapters)
export const chapterById = Object.fromEntries(ALL_CHAPTERS.map((c) => [c.id, c])) as Record<string, Chapter>
export const ALL_SUBTOPICS = ALL_CHAPTERS.flatMap((c) => c.subtopics.map((s) => ({ ...s, chapterId: c.id, subjectId: c.subjectId })))
export const subtopicById = Object.fromEntries(ALL_SUBTOPICS.map((s) => [s.id, s]))
export const HAS_FLASHCARDS = manifest.flashcards.length > 0

export const FORMULAS = formulasJson as Formula[]
export const formulaById = Object.fromEntries(FORMULAS.map((f) => [f.id, f])) as Record<string, Formula>

const contentCache = new Map<string, Promise<ChapterContent | undefined>>()
let questionsPromise: Promise<Question[]> | undefined
let flashPromise: Promise<Flashcard[]> | undefined

/** Forget loaded content, e.g. after the user's access changes. */
export function resetContentMemo() {
  contentCache.clear()
  questionsPromise = undefined
  flashPromise = undefined
}

async function remoteChapter(id: string): Promise<ChapterContent | undefined> {
  const [intro, questions] = await Promise.all([
    fetchRow<Pick<ChapterContent, 'reviewed' | 'intro'>>(`intro:${id}`),
    fetchRow<Question[]>(`questions:${id}`).catch(() => undefined),
  ])
  return intro ? { chapterId: id, reviewed: intro.reviewed, intro: intro.intro, questions: questions ?? [] } : undefined
}

/** Intro + questions of a chapter; undefined when it has none or (with accounts on) the user may not read it. */
export function loadChapterContent(id: string): Promise<ChapterContent | undefined> {
  if (!contentCache.has(id)) {
    const p = REMOTE ? remoteChapter(id) : contentByChapter[id] ? contentByChapter[id]().then((m) => m.default) : Promise.resolve(undefined)
    contentCache.set(id, p.catch((e) => { contentCache.delete(id); throw e }))
  }
  return contentCache.get(id)!
}

export function loadAllQuestions(): Promise<Question[]> {
  questionsPromise ??= (REMOTE
    ? fetchKind<Question[]>('questions').then((d) => d.flat())
    : Promise.all(ALL_CHAPTERS.filter((c) => c.written).map((c) => loadChapterContent(c.id)))
      .then((all) => all.flatMap((c) => c?.questions ?? []))
  ).catch((e) => { questionsPromise = undefined; throw e })
  return questionsPromise
}

export function loadAllFlashcards(): Promise<Flashcard[]> {
  flashPromise ??= (REMOTE
    ? fetchKind<Flashcard[]>('flashcards').then((d) => d.flat())
    : Promise.all(Object.values(flashByChapter).map((load) => load().then((m) => m.default.cards))).then((d) => d.flat())
  ).catch((e) => { flashPromise = undefined; throw e })
  return flashPromise
}

let bridgePromise: Promise<Bridge> | undefined
export function loadBridge(): Promise<Bridge> {
  bridgePromise ??= import('../../content/bridge.json').then((m) => m.default as Bridge)
  return bridgePromise
}

export function loadNotes(chapterId: string): Promise<NotesFile | undefined> {
  if (REMOTE) return fetchRow<NotesFile>(`notes:${chapterId}`)
  return notesByChapter[chapterId] ? notesByChapter[chapterId]().then((m) => m.default) : Promise.resolve(undefined)
}
